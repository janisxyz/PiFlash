val LocalUiText = staticCompositionLocalOf { UiText.En }

fun resolveUiText(languageTag: String): UiText {
    val tag = languageTag.ifBlank { Locale.getDefault().language }
    return when (tag.lowercase(Locale.ROOT)) {
        "de" -> UiText.De
        "fr" -> UiText.Fr
        "it" -> UiText.It
        "es" -> UiText.Es
        else -> UiText.En
    }
}
